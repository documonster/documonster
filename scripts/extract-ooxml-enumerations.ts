/**
 * Regenerate `src/test/fixtures/ooxml-enumerations.ts` from the ECMA-376 schemas.
 *
 * Run: `node scripts/extract-ooxml-enumerations.ts <dir>`
 *
 * `<dir>` holds the schemas of ECMA-376 5th edition (December 2016) in two folders: `Transitional/` from Part 4
 * (`OfficeOpenXML-XMLSchema-Transitional.zip`) and `Strict/` from Part 1 (`OfficeOpenXML-XMLSchema-Strict.zip`),
 * both downloadable from https://ecma-international.org/publications-and-standards/standards/ecma-376/. Only
 * `wml.xsd`, `sml.xsd` and `shared-commonSimpleTypes.xsd` are read.
 *
 * The vocabularies the readers and writers check are written by hand, and a hand-written list that is narrower
 * than the schema is a bug no round trip of this library's own output can find: the value never occurs until a
 * file from elsewhere carries it. The fixture is the second, mechanical source the tests hold them to. It lists
 * only the types something here checks; add a name to `TYPES` and rerun to cover another.
 */
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import process from "node:process";

const TYPES: Record<string, readonly string[]> = {
  wml: [
    "ST_Underline",
    "ST_HighlightColor",
    "ST_TextEffect",
    "ST_Em",
    "ST_CombineBrackets",
    "ST_Hint",
    "ST_Shd",
    "ST_Jc",
    "ST_JcTable",
    "ST_LineSpacingRule",
    "ST_TabJc",
    "ST_TabTlc",
    "ST_TextAlignment",
    "ST_TextDirection",
    "ST_DropCap",
    "ST_Wrap",
    "ST_HAnchor",
    "ST_VAnchor",
    "ST_TblWidth",
    "ST_TblLayoutType",
    "ST_HeightRule",
    "ST_VerticalJc",
    "ST_SectionMark",
    "ST_DocGrid",
    "ST_LineNumberRestart",
    "ST_PageBorderDisplay",
    "ST_PageBorderOffset",
    "ST_PageBorderZOrder"
  ],
  "shared-commonSimpleTypes": ["ST_VerticalAlignRun", "ST_XAlign", "ST_YAlign"],
  "dml-wordprocessingDrawing": [
    "ST_RelFromH",
    "ST_RelFromV",
    "ST_AlignH",
    "ST_AlignV",
    "ST_WrapText"
  ],
  "dml-chart": ["ST_LegendPos", "ST_DLblPos"],
  sml: [
    "ST_SheetState",
    "ST_Orientation",
    "ST_PageOrder",
    "ST_CellComments",
    "ST_PrintError",
    "ST_SheetViewType",
    "ST_Pane",
    "ST_PaneState"
  ]
};

function enumerations(xsd: string): Map<string, string[]> {
  const found = new Map<string, string[]>();
  for (const type of xsd.matchAll(
    /<xsd:simpleType name="(ST_\w+)"[^>]*>([\s\S]*?)<\/xsd:simpleType>/g
  )) {
    const values = [...type[2]!.matchAll(/<xsd:enumeration value="([^"]*)"/g)].map(v => v[1]!);
    if (values.length > 0) {
      found.set(type[1]!, values);
    }
  }
  return found;
}

async function main(): Promise<void> {
  const dir = process.argv[2];
  if (!dir) {
    throw new Error(
      "usage: node scripts/extract-ooxml-enumerations.ts <dir with Transitional/ and Strict/>"
    );
  }
  const lines: string[] = [];
  for (const [schema, names] of Object.entries(TYPES)) {
    const transitional = enumerations(
      await readFile(join(dir, "Transitional", `${schema}.xsd`), "utf8")
    );
    const strict = enumerations(await readFile(join(dir, "Strict", `${schema}.xsd`), "utf8"));
    lines.push(`  ${JSON.stringify(schema)}: {`);
    for (const name of names) {
      const t = transitional.get(name);
      const s = strict.get(name);
      if (!t || !s) {
        throw new Error(
          `${schema}.xsd: no enumeration ${name} in ${t ? "Strict" : "Transitional"}`
        );
      }
      const union = [...t, ...s.filter(v => !t.includes(v))];
      lines.push(`    ${name}: ${JSON.stringify(union)},`);
    }
    lines.push("  },");
  }
  const out = `/**
 * Enumerations of ECMA-376 5th edition (December 2016), Transitional and Strict together, by schema and type.
 *
 * Generated by \`scripts/extract-ooxml-enumerations.ts\` — do not edit by hand; rerun it instead.
 */
export const OOXML_ENUMERATIONS = {
${lines.join("\n")}
} as const;
`;
  const target = join(import.meta.dirname, "../src/test/fixtures/ooxml-enumerations.ts");
  await writeFile(target, out);
  process.stdout.write(`wrote ${target}\n`);
}

await main();
