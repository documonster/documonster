/**
 * Metrics of a face as Word lays text out with it, or `undefined` for a family
 * this table does not hold. A bold face falls back to the regular one, whose
 * vertical metrics it shares; an italic face to the upright one of its weight.
 */
export function getLayoutFontMetrics(
  fontName: string,
  bold?: boolean,
  italic?: boolean
): FontMetrics | undefined {
  let faces = layoutFacesByName.get(fontName);
  if (faces === undefined) {
    const key = fontName.toLowerCase();
    faces = Object.hasOwn(LAYOUT_FONT_METRICS, key) ? LAYOUT_FONT_METRICS[key]! : null;
    if (layoutFacesByName.size >= 1024) {
      layoutFacesByName.clear();
    }
    layoutFacesByName.set(fontName, faces);
  }
  if (!faces) {
    return undefined;
  }
  const upright = (bold ? faces[1] : undefined) ?? faces[0];
  return (italic ? (bold ? faces[3] : faces[2]) : undefined) ?? upright;
}

/** {@link LAYOUT_FONT_METRICS} by the name as asked for, which layout asks per word. */
const layoutFacesByName = new Map<string, LayoutFaces | null>();

/**
 * The ascent, descent (both positive) and line gap Word spaces a line of this
 * face by, in font units: the typo metrics when the face asks for them
 * (`USE_TYPO_METRICS`), otherwise `hhea`. A single-spaced line is their sum.
 */
export function getFontLineMetrics(metrics: FontMetrics): {
  ascent: number;
  descent: number;
  lineGap: number;
} {
  const h = metrics.header;
  if (h.useTypoMetrics) {
    return { ascent: h.sTypoAscender, descent: -h.sTypoDescender, lineGap: h.sTypoLineGap };
  }
  return {
    ascent: h.hheaAscender ?? h.usWinAscent,
    descent: -(h.hheaDescender ?? -h.usWinDescent),
    lineGap: h.hheaLineGap ?? 0
  };
}

